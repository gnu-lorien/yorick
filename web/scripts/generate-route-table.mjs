/**
 * Generate web/src/router/routeTable.ts from the legacy router.
 *
 * Run: npm run generate:routes
 *
 * There are 81 route patterns, several of them seven segments long, and a typo
 * in any one of them is a URL that silently stops working. So the table is
 * lifted out of public/scripts/app/routers/mobileRouter.js rather than
 * retyped, and regenerating it after a change to the legacy router shows the
 * difference as a diff.
 *
 * Order matters and is preserved: Backbone matches routes in declaration order
 * and takes the first hit, so `troupe/new` must stay ahead of `troupe/:id`.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const SOURCE = REPO + 'public/scripts/app/routers/mobileRouter.js';
const TARGET = REPO + 'web/src/router/routeTable.ts';

const src = fs.readFileSync(SOURCE, 'utf8');
const block = src.match(/routes:\s*\{[\s\S]*?\n        \}/);
if (!block) {
  console.error('could not find the routes block in', SOURCE);
  process.exit(1);
}

// Capture the trailing `// comment` too -- a few routes carry one, and it is
// the only documentation some of them have.
const entries = [...block[0].matchAll(/^\s*"([^"]*)"\s*:\s*"([^"]+)",?\s*(?:\/\/\s*(.*))?$/gm)].map(
  (m) => ({ pattern: m[1], handler: m[2], comment: (m[3] || '').trim() }),
);

if (!entries.length) {
  console.error('no routes parsed');
  process.exit(1);
}

const lines = entries.map((e) => {
  const comment = e.comment ? ` // ${e.comment}` : '';
  return `  { pattern: ${JSON.stringify(e.pattern)}, handler: ${JSON.stringify(e.handler)} },${comment}`;
});

const out = `/**
 * The legacy route table.
 *
 * GENERATED by web/scripts/generate-route-table.mjs from
 * public/scripts/app/routers/mobileRouter.js. Do not edit by hand; run
 * \`npm run generate:routes\` instead.
 *
 * Order is significant: Backbone tries routes in declaration order and takes
 * the first match, which is why \`troupe/new\` appears before \`troupe/:id\`.
 * The React router keeps that ordering and that first-match rule.
 *
 * \`handler\` is the legacy method name on mobileRouter. It is the key screens
 * register themselves under, so every entry here names the thing that has to
 * exist for the URL to work -- and the ones with no screen yet are exactly the
 * migration's remaining work.
 */

export interface RouteEntry {
  pattern: string;
  handler: string;
}

export const routeTable: RouteEntry[] = [
${lines.join('\n')}
];
`;

fs.writeFileSync(TARGET, out);
console.log(`wrote ${TARGET} with ${entries.length} routes`);
