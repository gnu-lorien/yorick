/**
 * Generate web/src/parse/venues/data.ts from the three venue models.
 *
 * Run: npm run generate:venues
 *
 * Each of Vampire.js, Werewolf.js and ChangelingBetaSlice.js opens with four
 * static tables:
 *
 *   ALL_SIMPLETRAIT_CATEGORIES   ~25 rows of [key, prettyName, groupName]
 *   TEXT_ATTRIBUTES              the free-text fields on the sheet
 *   TEXT_ATTRIBUTES_PRETTY_NAMES their labels, positionally paired
 *   SUM_CREATION_CATEGORIES      categories whose creation pool is a sum, not a count
 *
 * That is 76 category rows and 20 text attributes across the three, and a typo
 * in any one of them is a section that silently stops appearing on a character
 * sheet. So they are lifted by evaluating the literals rather than retyped, and
 * regenerating after a rules change shows the difference as a diff.
 *
 * Two entries in TEXT_ATTRIBUTES_PRETTY_NAMES are functions rather than
 * strings -- `function (character) { return "Faction"; }` for the vampire's
 * faction and the same shape for the changeling's kith group type. Both ignore
 * their argument and return a constant, so they are emitted as strings; see the
 * note this writes into the generated file.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const TARGET = REPO + 'web/src/parse/venues/data.ts';

const VENUES = [
  { name: 'Vampire', file: 'Vampire.js' },
  { name: 'Werewolf', file: 'Werewolf.js' },
  { name: 'ChangelingBetaSlice', file: 'ChangelingBetaSlice.js' },
];

/**
 * Pull `var NAME = <literal>;` out of a source file and evaluate it.
 *
 * Walks to the matching terminator tracking bracket depth and string state, so
 * a ";" inside a string or a nested array does not end the literal early.
 */
function literal(src, name) {
  const marker = `var ${name} = `;
  const start = src.indexOf(marker);
  if (start === -1) return undefined;
  const from = start + marker.length;
  let depth = 0;
  let inStr = null;
  for (let i = from; i < src.length; i++) {
    const ch = src[i];
    if (inStr) {
      if (ch === '\\') i++;
      else if (ch === inStr) inStr = null;
      continue;
    }
    if (ch === '"' || ch === "'") { inStr = ch; continue; }
    if (ch === '[' || ch === '{' || ch === '(') depth++;
    else if (ch === ']' || ch === '}' || ch === ')') depth--;
    else if (ch === ';' && depth === 0) return new Function(`return (${src.slice(from, i)});`)();
  }
  return undefined;
}

const venues = {};
const dynamicPrettyNames = [];

for (const venue of VENUES) {
  const src = fs.readFileSync(REPO + 'public/scripts/app/models/' + venue.file, 'utf8');
  const categories = literal(src, 'ALL_SIMPLETRAIT_CATEGORIES');
  const textAttributes = literal(src, 'TEXT_ATTRIBUTES');
  const rawPretty = literal(src, 'TEXT_ATTRIBUTES_PRETTY_NAMES') || [];
  const sumCreationCategories = literal(src, 'SUM_CREATION_CATEGORIES');

  if (!categories || !textAttributes || !sumCreationCategories) {
    console.error(`could not read the static tables out of ${venue.file}`);
    process.exit(1);
  }

  const prettyNames = rawPretty.map((entry, i) => {
    if (typeof entry !== 'function') return entry;
    const produced = entry(null);
    if (typeof produced !== 'string') {
      console.error(
        `${venue.name}: TEXT_ATTRIBUTES_PRETTY_NAMES[${i}] is a function that does not return a ` +
          `constant string. It cannot be flattened; the generated file needs a real function here.`,
      );
      process.exit(1);
    }
    dynamicPrettyNames.push(`${venue.name}.${textAttributes[i]} -> ${JSON.stringify(produced)}`);
    return produced;
  });

  if (prettyNames.length !== textAttributes.length) {
    console.error(
      `${venue.name}: TEXT_ATTRIBUTES has ${textAttributes.length} entries but ` +
        `TEXT_ATTRIBUTES_PRETTY_NAMES has ${prettyNames.length}. They are paired positionally, ` +
        `so a mismatch mislabels every field after the gap.`,
    );
    process.exit(1);
  }

  venues[venue.name] = { categories, textAttributes, prettyNames, sumCreationCategories };
}

const body = Object.entries(venues)
  .map(([name, v]) => {
    const categories = v.categories
      .map(([key, pretty, group]) =>
        `    { key: ${JSON.stringify(key)}, prettyName: ${JSON.stringify(pretty)}, group: ${JSON.stringify(group)} },`,
      )
      .join('\n');
    const textAttributes = v.textAttributes
      .map((key, i) => `    { key: ${JSON.stringify(key)}, label: ${JSON.stringify(v.prettyNames[i])} },`)
      .join('\n');
    return `  ${name}: {
    categories: [
${categories}
    ],
    textAttributes: [
${textAttributes}
    ],
    sumCreationCategories: ${JSON.stringify(v.sumCreationCategories)},
  },`;
  })
  .join('\n');

const out = `/**
 * The three venues' static tables.
 *
 * GENERATED by web/scripts/generate-venue-data.mjs from
 * public/scripts/app/models/{Vampire,Werewolf,ChangelingBetaSlice}.js.
 * Do not edit by hand; run \`npm run generate:venues\` instead.
 *
 * \`categories\` is ALL_SIMPLETRAIT_CATEGORIES, whose rows the legacy code reads
 * positionally as [key, prettyName, groupName]. Order is significant: it is the
 * order sections appear on a character sheet.
 *
 * \`textAttributes\` pairs TEXT_ATTRIBUTES with TEXT_ATTRIBUTES_PRETTY_NAMES,
 * which the legacy code keeps as two parallel arrays indexed together. Two of
 * those labels are written as \`function (character) { return "..."; }\` rather
 * than as strings -- the vampire's faction and the changeling's kith group
 * type. Both ignore the character and return a constant, so they are flattened
 * to strings here. The generator checks that: if either ever starts depending
 * on the character, it fails rather than silently freezing the wrong label.
 *
 * \`sumCreationCategories\` is SUM_CREATION_CATEGORIES -- the categories whose
 * creation pool is spent as a sum of trait values rather than as a count of
 * picks. Everywhere else a pick costs one slot; in these, a 3-point merit costs
 * three.
 */

export interface TraitCategory {
  /** The attribute name on the character, e.g. "disciplines". */
  key: string;
  /** The heading shown for it, e.g. "Disciplines". */
  prettyName: string;
  /** The sheet section it belongs to, e.g. "Attributes". */
  group: string;
}

export interface TextAttribute {
  key: string;
  label: string;
}

export interface VenueData {
  categories: TraitCategory[];
  textAttributes: TextAttribute[];
  sumCreationCategories: string[];
}

export const venueData: Record<'Vampire' | 'Werewolf' | 'ChangelingBetaSlice', VenueData> = {
${body}
};
`;

fs.mkdirSync(REPO + 'web/src/parse/venues', { recursive: true });
fs.writeFileSync(TARGET, out);

for (const [name, v] of Object.entries(venues)) {
  console.log(
    `${name.padEnd(20)} categories: ${String(v.categories.length).padStart(2)}` +
      `  textAttributes: ${v.textAttributes.length}` +
      `  sumCreation: ${v.sumCreationCategories.join(', ')}`,
  );
}
if (dynamicPrettyNames.length) {
  console.log('\nFlattened function labels: ' + dynamicPrettyNames.join('; '));
}
console.log(`\nwrote ${TARGET}`);
