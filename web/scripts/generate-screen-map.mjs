/**
 * Generate web/src/router/screenMap.ts from the legacy router.
 *
 * Run: npm run generate:routes
 *
 * For each handler in mobileRouter.js this records the jQuery Mobile page it
 * transitions to and the arguments it takes. Both matter to the migration:
 *
 * - The page id is what `.ui-page-active` reports, and the Playwright suite
 *   asserts on it (e2e/helpers/jqm-helpers.js `waitForActivePage`). Keeping the
 *   ids means the suite's navigation waits keep working against React.
 * - The argument list is the handler's signature, so a screen that has not been
 *   ported yet can still say what it would receive.
 *
 * A handler with no page id either redirects to another handler or renders into
 * the page it is already on; those are recorded with `pageId: null`.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const SOURCE = REPO + 'public/scripts/app/routers/mobileRouter.js';
const TARGET = REPO + 'web/src/router/screenMap.ts';

const src = fs.readFileSync(SOURCE, 'utf8');

// Handler definitions sit at exactly eight spaces of indent inside the
// Router.extend({...}) object literal.
const marks = [...src.matchAll(/^\s{8}([a-z_0-9]+):\s*function\s*\(([^)]*)\)\s*\{/gm)].map((m) => ({
  handler: m[1],
  args: m[2]
    .split(',')
    .map((a) => a.trim())
    .filter(Boolean),
  index: m.index,
}));

const handlers = marks.map((mark, i) => {
  const body = src.slice(mark.index, i + 1 < marks.length ? marks[i + 1].index : src.length);
  const pages = [...body.matchAll(/changePage\(\s*["']#([a-z0-9-]+)/gi)].map((x) => x[1]);
  return { ...mark, pages: [...new Set(pages)] };
});

// Only the handlers the route table actually dispatches to. The rest are
// internal helpers (show_character_helper, enforce_logged_in, ...).
const routed = new Set(
  [...src.matchAll(/^\s*"([^"]*)"\s*:\s*"([^"]+)",?\s*$/gm)].map((m) => m[2]),
);

const rows = handlers
  .filter((h) => routed.has(h.handler))
  .map((h) => {
    const pageId = h.pages.length ? h.pages[0] : null;
    const alt = h.pages.length > 1 ? h.pages.slice(1) : [];
    return `  ${h.handler}: { pageId: ${JSON.stringify(pageId)}, args: ${JSON.stringify(h.args)}${
      alt.length ? `, alsoUses: ${JSON.stringify(alt)}` : ''
    } },`;
  });

const out = `/**
 * What each legacy route handler renders.
 *
 * GENERATED by web/scripts/generate-screen-map.mjs from
 * public/scripts/app/routers/mobileRouter.js. Do not edit by hand; run
 * \`npm run generate:routes\` instead.
 *
 * \`pageId\` is the jQuery Mobile page the handler transitions to. The React
 * screens keep these ids, because \`.ui-page-active\` plus the id is how the
 * Playwright suite knows where it is.
 *
 * \`alsoUses\` lists further pages a handler can land on -- e.g.
 * \`character_show_approved\` shows the printable sheet or the "not approved"
 * page depending on the character.
 */

export interface ScreenInfo {
  pageId: string | null;
  args: string[];
  alsoUses?: string[];
}

export const screenMap: Record<string, ScreenInfo> = {
${rows.join('\n')}
};
`;

fs.writeFileSync(TARGET, out);
console.log(`wrote ${TARGET} with ${rows.length} handlers`);
