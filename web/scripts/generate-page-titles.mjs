/**
 * Generate web/src/router/pageTitles.ts from public/index.html.
 *
 * Run: npm run generate:routes
 *
 * jQuery Mobile pages carry their heading in `data-title`, and the legacy app
 * copies it into the header on every transition:
 *
 *   var current = $(".ui-page-active").jqmData("title");
 *   $("[data-role='header'] h1").text(current);
 *
 * -- public/scripts/app/main.js. The same string then picks the active navbar
 * tab, by matching it against the tab labels. So these are not captions; they
 * are the key two pieces of chrome are driven by, and they are extracted rather
 * than retyped.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const SOURCE = REPO + 'public/index.html';
const TARGET = REPO + 'web/src/router/pageTitles.ts';

const html = fs.readFileSync(SOURCE, 'utf8');

// Attribute order varies across the file, so match the whole opening tag of
// anything with data-role="page" and pull id and data-title out of it.
const pages = [...html.matchAll(/<div\b([^>]*\bdata-role="page"[^>]*)>/g)]
  .map((m) => {
    const attrs = m[1];
    const id = attrs.match(/\bid="([^"]+)"/)?.[1];
    const title = attrs.match(/\bdata-title="([^"]*)"/)?.[1];
    return id ? { id, title: title ?? null } : null;
  })
  .filter(Boolean);

if (!pages.length) {
  console.error('no pages found in', SOURCE);
  process.exit(1);
}

const rows = pages.map((p) => `  ${JSON.stringify(p.id)}: ${JSON.stringify(p.title)},`);

const out = `/**
 * Each jQuery Mobile page's heading.
 *
 * GENERATED by web/scripts/generate-page-titles.mjs from public/index.html.
 * Do not edit by hand; run \`npm run generate:routes\` instead.
 *
 * The header shows this, and the footer navbar marks the tab whose label
 * matches it -- both behaviours from public/scripts/app/main.js. A null means
 * the page declared no \`data-title\`, and the legacy header would have shown
 * an empty heading.
 */

export const pageTitles: Record<string, string | null> = {
${rows.join('\n')}
};

/** The heading for a page id, or an empty string if it has none. */
export function titleFor(pageId: string): string {
  return pageTitles[pageId] ?? '';
}
`;

fs.writeFileSync(TARGET, out);
console.log(`wrote ${TARGET} with ${pages.length} pages`);
